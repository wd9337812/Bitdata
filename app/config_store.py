def config_path() -> Path:
    return Path(os.getenv("APP_CONFIG_PATH", "./data/config.json"))


def load_config(include_secret: bool = True) -> dict[str, Any]:
    path = config_path()
    config = DEFAULT_CONFIG.copy()
    loaded: dict[str, Any] = {}
    if path.exists():
        with path.open("r", encoding="utf-8") as file:
            loaded = json.load(file)
            config.update(loaded)
    # V4.3 uses strategy-neutral execution names while accepting older saved files.
    if "execution_max_spread_pct" not in loaded and "opportunity_v3_max_spread_pct" in loaded:
        config["execution_max_spread_pct"] = loaded["opportunity_v3_max_spread_pct"]
    if "execution_min_depth_notional_usdt" not in loaded and "opportunity_v3_min_depth_notional_usdt" in loaded:
        config["execution_min_depth_notional_usdt"] = loaded["opportunity_v3_min_depth_notional_usdt"]
    if not include_secret:
        config["api_secret"] = "********" if config.get("api_secret") else ""
        config["api_key"] = mask(config.get("api_key", ""))
    return config


def save_config(payload: dict[str, Any]) -> dict[str, Any]:
    current = load_config(include_secret=True)
    if "api_key" in payload and isinstance(payload.get("api_key"), str):
        payload["api_key"] = payload["api_key"].strip()
    if "api_secret" in payload and isinstance(payload.get("api_secret"), str):
        payload["api_secret"] = payload["api_secret"].strip()
    if "binance_base_url" in payload and isinstance(payload.get("binance_base_url"), str):
        payload["binance_base_url"] = payload["binance_base_url"].strip()
    if payload.get("api_secret") in {"", "********"} and current.get("api_secret"):
        payload = {key: value for key, value in payload.items() if key != "api_secret"}
    if (
        ("..." in str(payload.get("api_key", "")) or payload.get("api_key") in {"", "****"})
        and current.get("api_key")
    ):
        payload = {key: value for key, value in payload.items() if key != "api_key"}
    manual_mode = str(payload.get("stage_manual_mode", current.get("stage_manual_mode", "auto")) or "auto")
    if manual_mode == "auto":
        payload["stage_manual_until"] = ""
    elif not payload.get("stage_manual_until"):
        hours = float(payload.get("stage_manual_default_hours", current.get("stage_manual_default_hours", 6.0)))
        payload["stage_manual_until"] = (datetime.now(timezone.utc) + timedelta(hours=hours)).isoformat()
    current.update(payload)
    path = config_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f"{path.name}.{os.getpid()}.{uuid.uuid4().hex}.tmp")
    with tmp.open("w", encoding="utf-8") as file:
        json.dump(current, file, ensure_ascii=False, indent=2)
    tmp.replace(path)
    return load_config(include_secret=False)


def mask(value: str) -> str:
    if not value:
        return ""
    if len(value) <= 8:
        return "****"
    return f"{value[:4]}...{value[-4:]}"
